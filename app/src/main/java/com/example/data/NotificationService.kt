package com.example.data

import android.util.Log
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import okhttp3.MediaType.Companion.toMediaTypeOrNull
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody.Companion.toRequestBody
import org.json.JSONObject
import java.net.URLEncoder

class NotificationService(private val okHttpClient: OkHttpClient) {

    suspend fun verifyAndConnectTelegram(botToken: String, chatId: String, verificationMessage: String): Pair<Boolean, String> {
        return withContext(Dispatchers.IO) {
            val cleanToken = botToken.trim().removePrefix("bot").trim()
            val cleanChatId = chatId.trim()

            if (cleanToken.isBlank() || cleanChatId.isBlank()) {
                return@withContext false to "Bot token and Telegram Chat ID are both required."
            }

            // Step 1: Verify Bot Token validity with Telegram getMe API
            var botUsername = "Bot"
            try {
                val getMeUrl = "https://api.telegram.org/bot$cleanToken/getMe"
                val getMeRequest = Request.Builder().url(getMeUrl).get().build()
                okHttpClient.newCall(getMeRequest).execute().use { response ->
                    val body = response.body?.string().orEmpty()
                    if (!response.isSuccessful || body.isBlank()) {
                        return@withContext false to "Invalid Telegram Bot Token. Verify the token copied from @BotFather."
                    }
                    val json = JSONObject(body)
                    if (!json.optBoolean("ok", false)) {
                        val desc = json.optString("description", "Invalid Bot Token")
                        return@withContext false to "Telegram error: $desc. Check your token from @BotFather."
                    }
                    val result = json.optJSONObject("result")
                    botUsername = result?.optString("username") ?: result?.optString("first_name") ?: "Bot"
                }
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                return@withContext false to "Network error validating Telegram bot: ${e.message ?: e.javaClass.simpleName}"
            }

            // Step 2: Deliver verification message to the specified Chat ID
            try {
                val sendUrl = "https://api.telegram.org/bot$cleanToken/sendMessage"
                val json = JSONObject().apply {
                    put("chat_id", cleanChatId)
                    put("text", verificationMessage)
                }

                val requestBody = json.toString().toRequestBody("application/json".toMediaTypeOrNull())
                val request = Request.Builder()
                    .url(sendUrl)
                    .post(requestBody)
                    .build()

                okHttpClient.newCall(request).execute().use { response ->
                    val body = response.body?.string().orEmpty()
                    if (response.isSuccessful) {
                        Log.d("DestinedFX_Notification", "Telegram message sent successfully to @$botUsername.")
                        return@withContext true to "Connected to @$botUsername! Verification alert delivered to Chat ID $cleanChatId."
                    } else {
                        val errorJson = runCatching { JSONObject(body) }.getOrNull()
                        val desc = errorJson?.optString("description", "").orEmpty()
                        Log.e("DestinedFX_Notification", "Telegram send error: $desc")
                        val helpfulMsg = when {
                            desc.contains("chat not found", ignoreCase = true) || desc.contains("Forbidden", ignoreCase = true) ->
                                "Bot @$botUsername is valid, but cannot reach Chat ID $cleanChatId. Open Telegram, search for @$botUsername, tap START, then tap Connect again."
                            desc.contains("Unauthorized", ignoreCase = true) ->
                                "Unauthorized token. Re-check the token generated by @BotFather."
                            else -> "Telegram API error: ${desc.ifBlank { "HTTP " + response.code }}"
                        }
                        return@withContext false to helpfulMsg
                    }
                }
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e("DestinedFX_Notification", "Telegram API error: ${e.javaClass.simpleName}")
                return@withContext false to "Telegram dispatch failed: ${e.message ?: e.javaClass.simpleName}"
            }
        }
    }

    suspend fun sendTelegramMessage(botToken: String, chatId: String, message: String): Boolean {
        return withContext(Dispatchers.IO) {
            try {
                val cleanToken = botToken.trim().removePrefix("bot").trim()
                val cleanChatId = chatId.trim()
                if (cleanToken.isBlank() || cleanChatId.isBlank()) return@withContext false

                val url = "https://api.telegram.org/bot$cleanToken/sendMessage"
                val json = JSONObject().apply {
                    put("chat_id", cleanChatId)
                    put("text", message)
                }

                val requestBody = json.toString().toRequestBody("application/json".toMediaTypeOrNull())
                val request = Request.Builder()
                    .url(url)
                    .post(requestBody)
                    .build()

                okHttpClient.newCall(request).execute().use { response ->
                    response.isSuccessful
                }
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e("DestinedFX_Notification", "Telegram API error: ${e.javaClass.simpleName}")
                false
            }
        }
    }

    suspend fun sendWhatsAppMessage(apiKey: String, phoneNumber: String, message: String): Boolean {
        return withContext(Dispatchers.IO) {
            try {
                if (apiKey.isBlank() || phoneNumber.isBlank()) return@withContext false

                val cleanPhone = phoneNumber.replace("+", "").replace(" ", "")
                val encodedMsg = URLEncoder.encode(message, "UTF-8")
                val url = "https://api.callmebot.com/whatsapp.php?phone=$cleanPhone&text=$encodedMsg&apikey=$apiKey"

                val request = Request.Builder()
                    .url(url)
                    .get()
                    .build()

                okHttpClient.newCall(request).execute().use { response ->
                    response.isSuccessful
                }
            } catch (e: kotlinx.coroutines.CancellationException) {
                throw e
            } catch (e: Exception) {
                Log.e("DestinedFX_Notification", "WhatsApp API error: ${e.javaClass.simpleName}")
                false
            }
        }
    }
}
