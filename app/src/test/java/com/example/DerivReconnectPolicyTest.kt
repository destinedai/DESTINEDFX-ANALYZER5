package com.example

import com.example.service.retryFreshDerivAuthorization
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test

class DerivReconnectPolicyTest {
    @Test
    fun everyRetryInvokesFreshAuthorizationProviderAndIsBounded() = runBlocking {
        val requestedOtps = mutableListOf<String>()
        var attemptEvents = 0
        val connected = retryFreshDerivAuthorization(
            maxAttempts = 3,
            shouldContinue = { true },
            onAttempt = { attemptEvents++ },
            pause = {},
            reconnect = {
                // Synthetic values model the one-time OTP generated by a fresh gateway authorization call.
                val otp = "synthetic-otp-${requestedOtps.size + 1}"
                requestedOtps += otp
                if (requestedOtps.size < 3) Result.failure(IllegalStateException("synthetic expired session"))
                else Result.success("fresh-session")
            }
        )

        assertTrue(connected)
        assertEquals(3, attemptEvents)
        assertEquals(listOf("synthetic-otp-1", "synthetic-otp-2", "synthetic-otp-3"), requestedOtps)
        assertEquals(requestedOtps.size, requestedOtps.toSet().size)
    }

    @Test
    fun retryStopsWhenOwnerStopsServiceAndNeverExceedsConfiguredAttempts() = runBlocking {
        var calls = 0
        var continueRecovery = true
        val connected = retryFreshDerivAuthorization(
            maxAttempts = 5,
            shouldContinue = { continueRecovery },
            onAttempt = { if (it == 0) continueRecovery = false },
            pause = {},
            reconnect = { calls++; Result.failure(IllegalStateException("synthetic failure")) }
        )
        assertEquals(false, connected)
        assertEquals(1, calls)
    }
}
